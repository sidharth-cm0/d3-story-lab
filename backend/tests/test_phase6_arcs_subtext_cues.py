def test_08_subjective_false_belief_preservation():
    """8. Subjective false belief: character believing P=False says 'P is false' -> TRUTHFUL, NOT LYING."""
    world = WorldState(id="world_fb", name="False Belief World")
    prop = Proposition(
        id="prop_dossier_safe",
        subject="dossier",
        predicate="is_in",
        object="safe",
        truth_value=True,  # Canonically TRUE in objective reality
    )
    world.propositions[prop.id] = prop

    char = Character(
        id="char_bob",
        name="Bob",
        role="Analyst",
        current_location_id="loc_office",
        emotional_state=EmotionalState(fear=0.1, anger=0.1, trust=0.5, curiosity=0.3),
    )
    # Bob subjectively believes the proposition is FALSE
    char.knowledge[prop.id] = KnowledgeItem(
        proposition_id=prop.id,
        holder_id=char.id,
        believed_truth_value=False,
        certainty=0.9,
        source="inferred",
    )
    world.characters[char.id] = char

    analyzer = SubtextAnalyzer()
    # Bob says: "I don't have it, the dossier is not in the safe."
    analysis = analyzer.analyze(
        speaker=char,
        dialogue="I haven't seen any dossier in the safe.",
        world=world,
        listener_id="char_alice",
    )

    # Invariant: Because Bob subjectively believes it is False, asserting it is False is TRUTHFUL, not LYING
    assert analysis.spoken_intent == DeceptionClassification.TRUTHFUL
    assert analysis.primary_classification == DeceptionClassification.TRUTHFUL
    assert DeceptionClassification.LYING not in analysis.classifications


