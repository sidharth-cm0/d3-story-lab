def test_06_transient_emotion_spike_does_not_register_as_turning_point():
    """6. Transient emotion spike that reverts to baseline does NOT register as a turning point."""
    world = WorldState(id="world_spike", name="Transient Spike World", current_tick=6)
    char = Character(
        id="char_sara",
        name="Sara",
        role="Scientist",
        current_location_id="loc_lab",
        emotional_state=EmotionalState(fear=0.2, anger=0.1, trust=0.2, curiosity=0.5),
    )
    world.characters[char.id] = char

    events = [
        # Baseline at tick 1
        Event(
            id="ev_base",
            tick=1,
            event_type=EventType.CHARACTER_MOVED,
            actor_ids=[char.id],
            description="Sara enters the laboratory.",
        ),
        # Transient spike at tick 2: fear spikes to 0.8
        Event(
            id="ev_spike",
            tick=2,
            event_type=EventType.EMOTION_CHANGED,
            actor_ids=[char.id],
            description="Sara jumps at a sudden loud crash in the shadows.",
            metadata={"emotional_state": {"fear": 0.8, "anger": 0.1, "trust": 0.2, "curiosity": 0.5}},
        ),
        # Reverts at tick 3: fear settles back to baseline 0.2
        Event(
            id="ev_revert",
            tick=3,
            event_type=EventType.EMOTION_CHANGED,
            actor_ids=[char.id],
            description="Sara chuckles realising it was just an empty beaker.",
            metadata={"emotional_state": {"fear": 0.2, "anger": 0.1, "trust": 0.2, "curiosity": 0.5}},
        ),
    ]
    for e in events:
        world.events[e.id] = e

    tracker = CharacterArcTracker()
    arc = tracker.trace_arc(char.id, world, events)

    # The spike event "ev_spike" must NOT be registered as a persistent turning point
    tp_event_ids = [tp.event_id for tp in arc.turning_points]
    assert "ev_spike" not in tp_event_ids


